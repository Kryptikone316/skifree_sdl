#!/usr/bin/env python3
"""8-bit theme assets, derived from the 16-bit sprite pack: every sprite is reduced to half resolution (2x2 blocks,
keeping the original size so hitboxes do not change) and snapped to one fixed palette.
Also writes the palette as a C header for the game's palette filter, so art and filter always agree.
Usage: make_sprites8.py <16-bit-pack-dir> <out-dir> <palette8.h>"""
import sys, os, glob, re
from PIL import Image

KEY = (255, 255, 255)
PAL = [   # one retro palette: snow, blues, grays, greens, browns, reds/oranges/yellows, magentas, skin, cyans
    (0, 0, 0), (252, 252, 254), (236, 242, 252), (200, 216, 244), (150, 176, 228), (96, 132, 212), (52, 84, 196), (24, 40, 140),
    (188, 190, 204), (140, 142, 160), (100, 102, 124), (60, 62, 84), (28, 32, 46),
    (18, 84, 52), (34, 122, 74), (72, 168, 98), (140, 214, 140),
    (112, 70, 36), (156, 100, 54), (200, 150, 90),
    (222, 36, 40), (250, 112, 100), (250, 140, 20), (255, 226, 70), (246, 210, 40), (170, 128, 10),
    (216, 56, 196), (248, 136, 228), (146, 26, 128), (140, 60, 200),
    (240, 200, 70), (60, 214, 230), (150, 232, 242), (40, 94, 226), (38, 172, 54), (150, 30, 40),
]

def nearest(c):
    r, g, b = c
    best, bd = None, 1e18
    for p in PAL:
        d = (2 * (r - p[0]) ** 2 + 4 * (g - p[1]) ** 2 + 3 * (b - p[2]) ** 2)
        if d < bd: best, bd = p, d
    return best

def lum(c): return (c[0] * 299 + c[1] * 587 + c[2] * 114) // 1000

# Sprites with fine lettering (OUCH!, WOOF!, the signs and flags) cannot be halved legibly: they keep their 16-bit
# drawing and are only snapped to the palette.
SKIP = {12, 35, 36, 57, 58, 59, 60, 61, 62, 63}
TIE_LIGHT = set(range(68, 82))                                     # the yeti: dark outlines would swallow its face
DARK_TEXT = set()
LIGHT_TEXT = set()

def sat(c): return max(c) - min(c)

def reduce(im, method='mode', tie_light=False, accent=False):
    w, h = im.size
    bw, bh = (w + 1) // 2, (h + 1) // 2
    out = Image.new('RGB', (bw * 2, bh * 2), KEY)
    for by in range(bh):
        for bx in range(bw):
            px = [im.getpixel((x, y)) for y in (by * 2, by * 2 + 1) for x in (bx * 2, bx * 2 + 1) if x < w and y < h]
            solid = [p for p in px if p != KEY]
            if len(solid) < 2: continue
            qs = [nearest(p) for p in solid]
            counts = {}
            for q in qs: counts[q] = counts.get(q, 0) + 1
            top = max(counts.values())
            tied = [c for c, n in counts.items() if n == top]
            hot = [p for p in qs if sat(p) >= 150] if accent else []   # small bright details (eyes, teeth) win the block
            q = max(tied, key=lum) if tie_light else min(tied, key=lum)            # most common colour; ties go darker (lighter for TIE_LIGHT)
            if hot: q = max(hot, key=sat)
            if method == 'dark':
                d = min(qs, key=lum)
                if lum(d) < 90: q = d
            elif method == 'light':
                l = max(qs, key=lum)
                if lum(l) > 215: q = l
            for y in (0, 1):
                for x in (0, 1): out.putpixel((bx * 2 + x, by * 2 + y), q)
    return out.crop((0, 0, w, h))

if __name__ == '__main__':
    src, dst, hdr = sys.argv[1:4]
    os.makedirs(dst, exist_ok=True)
    n = 0
    for f in sorted(glob.glob(os.path.join(src, 'ski32_*.bmp'))):
        im = Image.open(f).convert('RGB')
        sid = int(re.findall(r'(\d+)', os.path.basename(f))[-1])
        if sid in SKIP:   # lettered sprites: not halved, only snapped to the palette (keeps the text legible)
            q = Image.new('RGB', im.size, KEY)
            for yy in range(im.height):
                for xx in range(im.width):
                    px = im.getpixel((xx, yy))
                    if px != KEY: q.putpixel((xx, yy), nearest(px))
            q.save(os.path.join(dst, os.path.basename(f)), format='BMP'); n += 1
            continue
        reduce(im, 'dark' if sid in DARK_TEXT else ('light' if sid in LIGHT_TEXT else 'mode'), sid in TIE_LIGHT, sid in TIE_LIGHT).save(os.path.join(dst, os.path.basename(f)), format='BMP')
        n += 1
    with open(hdr, 'w') as h:
        h.write('/* generated by tools/make_sprites8.py: the 8-bit theme palette (RGB) */\n')
        h.write('#define PAL8_N %d\nstatic const unsigned char k_pal8[PAL8_N][3] = {\n' % len(PAL))
        h.write(',\n'.join('    { %d, %d, %d }' % p for p in PAL) + '\n};\n')
    print(n, 'sprites ->', dst, ',', len(PAL), 'colours ->', hdr)
